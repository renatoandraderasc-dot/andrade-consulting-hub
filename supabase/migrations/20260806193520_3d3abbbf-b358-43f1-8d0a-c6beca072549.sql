CREATE TABLE public.analise_anual (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  store_id uuid NOT NULL REFERENCES public.stores(id) ON DELETE CASCADE,
  ano integer NOT NULL,
  mes integer NOT NULL CHECK (mes BETWEEN 1 AND 12),
  faturamento numeric NOT NULL DEFAULT 0,
  lucro numeric NOT NULL DEFAULT 0,
  volume numeric NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (store_id, ano, mes)
);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.analise_anual TO authenticated;
GRANT ALL ON public.analise_anual TO service_role;

ALTER TABLE public.analise_anual ENABLE ROW LEVEL SECURITY;

CREATE POLICY "analise_anual_select" ON public.analise_anual FOR SELECT TO authenticated
USING (
  public.has_role(auth.uid(), 'admin')
  OR EXISTS (
    SELECT 1 FROM public.user_store_access a
    WHERE a.user_id = auth.uid() AND a.store_id = analise_anual.store_id AND a.approved
  )
);

CREATE POLICY "analise_anual_admin" ON public.analise_anual FOR ALL TO authenticated
USING (public.has_role(auth.uid(), 'admin'))
WITH CHECK (public.has_role(auth.uid(), 'admin'));

